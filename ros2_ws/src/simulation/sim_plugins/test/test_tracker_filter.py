"""
sim_plugins/test/test_tracker_filter.py -- PURPOSE: unit tests of the filtered copy of the team's launch file
(tracker_filter.py), run on the REAL main/launch/tracker.launch.xml: a custom detector removes exactly new_od,
a custom mission brain exactly main_controller.py, everything else stays, and the team file is never changed.
"""

import xml.etree.ElementTree as ET
from pathlib import Path

import pytest

from sim_plugins import tracker_filter as tf

TRACKER = Path(__file__).resolve().parents[3] / 'main' / 'launch' / 'tracker.launch.xml'


def nodes(text):
    return [(n.get('pkg'), n.get('exec')) for n in ET.fromstring(text.split('\n', 1)[1]).iter('node')]


@pytest.fixture
def tracker_text():
    if not TRACKER.is_file():
        pytest.skip('the team package main is not in this checkout')
    return TRACKER.read_text(encoding='utf-8')


def test_without_new_od(tracker_text):
    before = nodes(tracker_text)
    text, removed = tf.filter_tracker_xml(tracker_text, [tf.REPLACEABLE['detector']])
    after = nodes(text)
    assert removed == ['detection/new_od']
    assert ('detection', 'new_od') not in after
    assert [n for n in before if n != ('detection', 'new_od')] == after       # everything else, same order
    assert ('main', 'main_controller.py') in after and ('video_cam', 'siyi') in after
    assert '<arg name="debug"' in text or "name=\"debug\"" in text            # arguments are kept


def test_without_both(tracker_text):
    text, removed = tf.filter_tracker_xml(tracker_text, list(tf.REPLACEABLE.values()))
    assert sorted(removed) == ['detection/new_od', 'main/main_controller.py']
    after = nodes(text)
    assert ('waypoint_mavros', 'waypoint') in after and ('mapping', 'trigger') in after


def test_write_filtered_leaves_the_team_file_alone(tracker_text, tmp_path):
    out, removed, notes = tf.write_filtered(str(TRACKER), [('detection', 'new_od'), ('nope', 'missing')], tmp_path)
    assert Path(out).parent == tmp_path and Path(out).name.startswith('tracker_without_')
    assert removed == ['detection/new_od'] and 'nope/missing' in notes[0]
    assert TRACKER.read_text(encoding='utf-8') == tracker_text
    assert 'GENERATED by sim_plugins' in Path(out).read_text()


def test_nodes_inside_groups_and_errors():
    text = '<launch><group><node pkg="detection" exec="new_od"/><node pkg="a" exec="b"/></group></launch>'
    new, removed = tf.filter_tracker_xml(text, [('detection', 'new_od')])
    assert removed == ['detection/new_od'] and nodes(new) == [('a', 'b')]
    with pytest.raises(ValueError, match='not valid XML'):
        tf.filter_tracker_xml('<launch>', [])
    with pytest.raises(ValueError, match='not a ROS 2 launch file'):
        tf.filter_tracker_xml('<robot/>', [])
