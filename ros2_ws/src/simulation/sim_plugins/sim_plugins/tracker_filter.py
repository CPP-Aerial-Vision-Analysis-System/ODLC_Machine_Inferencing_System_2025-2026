"""
sim_plugins/tracker_filter.py -- PURPOSE: make a copy of the team's main/launch/tracker.launch.xml WITHOUT the
nodes that a profile replaces, so a teammate's detector or mission brain runs INSTEAD of the team's one.

Why a filtered copy (and not "run both"):
  * two detectors on /image_detection: main_controller cannot tell their results apart;
  * two mission brains: both switch flight modes and insert waypoints, and fight each other;
  * new_od loads a YOLO model onto the graphics card even when it has nothing to do, and the laptop's
    8 GB card is shared with Gazebo.
The team's file itself is never changed: team_stack.launch.py includes this copy instead (only when a
profile replaces a node; without a profile it includes the original, exactly as before).

    filter_tracker_xml(text, [('detection', 'new_od')])  -> (new text, ['detection/new_od'])

Nodes are matched by their pkg + exec attributes, the same pair `ros2 run <pkg> <exec>` uses. Everything
else in the file (arguments, set_parameter, the debug image_view, other nodes) is kept as it is. XML
comments (the team's commented-out nodes) are dropped from the copy: they never start anything anyway.
"""

from __future__ import annotations

import xml.etree.ElementTree as ET
from pathlib import Path
from typing import List, Sequence, Tuple

#: The team node each replaceable slot stands for: (pkg, exec) in tracker.launch.xml.
REPLACEABLE = {
    'detector': ('detection', 'new_od'),
    'mission_brain': ('main', 'main_controller.py'),
}

HEADER = ('<!-- GENERATED by sim_plugins (tracker_filter.py) from {source}\n'
          '     The team\'s tracker.launch.xml WITHOUT: {removed}\n'
          '     (a plug-in profile replaces them). Do not edit: it is rewritten at every start. -->\n')


def filter_tracker_xml(text: str, remove: Sequence[Tuple[str, str]], source: str = 'tracker.launch.xml'
                       ) -> Tuple[str, List[str]]:
    """Remove the <node pkg=P exec=E> elements listed in `remove` from a ROS 2 XML launch file text.

    Returns (new XML text, ['pkg/exec' of every node that was removed]). Raises ValueError when the text
    is not an XML launch file (root element <launch>).
    """
    try:
        root = ET.fromstring(text)
    except ET.ParseError as exc:
        raise ValueError(f'{source} is not valid XML: {exc}') from None
    if root.tag != 'launch':
        raise ValueError(f'{source} is not a ROS 2 launch file (its root element is <{root.tag}>)')
    wanted = {(str(p), str(e)) for p, e in remove}
    removed: List[str] = []

    def walk(parent: ET.Element) -> None:
        for child in list(parent):
            if child.tag == 'node' and (child.get('pkg'), child.get('exec')) in wanted:
                parent.remove(child)
                removed.append(f'{child.get("pkg")}/{child.get("exec")}')
            else:
                walk(child)            # nodes inside <group> are found too

    walk(root)
    body = ET.tostring(root, encoding='unicode')
    header = HEADER.format(source=source, removed=', '.join(removed) or 'nothing')
    return '<?xml version="1.0" encoding="UTF-8"?>\n' + header + body + '\n', removed


def write_filtered(tracker_path: str, remove: Sequence[Tuple[str, str]], out_dir: Path
                   ) -> Tuple[str, List[str], List[str]]:
    """Write the filtered copy next to the other generated files.

    Returns (path of the copy, removed 'pkg/exec' list, notes). A node that was asked for but is not in the
    file is reported in the notes (the team may have renamed it): the copy is still written.
    """
    text = Path(tracker_path).read_text(encoding='utf-8')
    new_text, removed = filter_tracker_xml(text, remove, source=str(tracker_path))
    notes = [f'{p}/{e} is not in {tracker_path}: nothing to remove for it'
             for p, e in remove if f'{p}/{e}' not in removed]
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    tag = '_'.join(e.replace('.py', '') for _, e in remove) or 'none'
    out = out_dir / f'tracker_without_{tag}.launch.xml'
    out.write_text(new_text, encoding='utf-8')
    return str(out), removed, notes
