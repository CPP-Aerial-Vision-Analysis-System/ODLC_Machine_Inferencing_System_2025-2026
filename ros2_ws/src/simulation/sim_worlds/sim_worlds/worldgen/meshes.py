"""
sim_worlds/worldgen/meshes.py -- PURPOSE: write the few small 3D meshes the worlds need as Wavefront OBJ files
(plain text: vertices "v", texture coordinates "vt", normals "vn", triangles "f").

  ground_mesh()   a flat square grid whose texture coordinates repeat every `repeat_m` metres (an SDF <plane>
                  cannot repeat a texture, so the ground is this mesh)
  quad_mesh()     one textured square (used for the dirt / dry / lush grass patches)
  ribbon_mesh()   a strip that follows a polyline (the creek)
  dome_mesh()     the pop-up dome tent: half an ellipsoid with an open door on its +x side

All meshes use metres, z up, and triangles that are counter-clockwise when seen from outside.
"""

import math
import os

import numpy as np


def write_obj(path, verts, uvs, normals, faces, comment=''):
    """Write an OBJ file. verts/uvs/normals: lists of tuples; faces: list of triangles, each a tuple of three
    (vertex, uv, normal) index triples (0-based; OBJ itself counts from 1).

    A one-line white material file (<name>.mtl) is written next to it so Gazebo's OBJ loader does not warn
    "Missing material"; the SDF <material> of the visual replaces it anyway.
    """
    base = os.path.splitext(os.path.basename(path))[0]
    with open(os.path.splitext(path)[0] + '.mtl', 'w', encoding='utf-8', newline='\n') as f:
        f.write(f'# white placeholder material for {base}.obj (the SDF <material> replaces it)\n'
                'newmtl white\nKa 1 1 1\nKd 1 1 1\nKs 0 0 0\nd 1\n')
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(f'# {comment}\n# generated by sim_worlds/worldgen/meshes.py (metres, z up)\n'
                f'mtllib {base}.mtl\nusemtl white\n')
        for v in verts:
            f.write(f'v {v[0]:.4f} {v[1]:.4f} {v[2]:.4f}\n')
        for t in uvs:
            f.write(f'vt {t[0]:.5f} {t[1]:.5f}\n')
        for n in normals:
            f.write(f'vn {n[0]:.4f} {n[1]:.4f} {n[2]:.4f}\n')
        for face in faces:
            f.write('f ' + ' '.join(f'{a + 1}/{b + 1}/{c + 1}' for a, b, c in face) + '\n')


def ground_mesh(path, half_size_m, cell_m, repeat_m):
    """Flat square grid from -half_size_m to +half_size_m (centred on the origin); the texture repeats every
    repeat_m metres (an SDF <plane> cannot repeat a texture, so the ground is this mesh)."""
    n = int(math.ceil(2 * half_size_m / cell_m))
    verts, uvs = [], []
    for j in range(n + 1):
        for i in range(n + 1):
            x = -half_size_m + i * (2 * half_size_m / n)
            y = -half_size_m + j * (2 * half_size_m / n)
            verts.append((x, y, 0.0))
            uvs.append((x / repeat_m, y / repeat_m))
    faces = []
    for j in range(n):
        for i in range(n):
            a = j * (n + 1) + i
            b, c = a + 1, a + n + 1
            d = c + 1
            faces.append(((a, a, 0), (b, b, 0), (d, d, 0)))
            faces.append(((a, a, 0), (d, d, 0), (c, c, 0)))
    write_obj(path, verts, uvs, [(0.0, 0.0, 1.0)], faces,
              f'ground {2 * half_size_m:.0f} m square, texture repeats every {repeat_m} m')


def quad_mesh(path, sx=1.0, sy=1.0, comment='unit quad', z=0.0):
    """One textured quad centred on the origin at height z, facing up. Texture u runs along +x, v along +y,
    so a north-up camera sees the picture upright (a textured SDF <box> maps it turned by 90 degrees)."""
    verts = [(-sx / 2, -sy / 2, z), (sx / 2, -sy / 2, z), (sx / 2, sy / 2, z), (-sx / 2, sy / 2, z)]
    uvs = [(0, 0), (1, 0), (1, 1), (0, 1)]
    faces = [((0, 0, 0), (1, 1, 0), (2, 2, 0)), ((0, 0, 0), (2, 2, 0), (3, 3, 0))]
    write_obj(path, verts, uvs, [(0, 0, 1)], faces, comment)


def ribbon_mesh(path, centreline, width, z, repeat_m, comment='ribbon'):
    """A strip `width` metres wide following centreline [(x, y), ...] at height z; u repeats every repeat_m."""
    pts = np.asarray(centreline, dtype=float)
    seg = np.diff(pts, axis=0)
    s = np.concatenate([[0.0], np.cumsum(np.hypot(seg[:, 0], seg[:, 1]))])
    verts, uvs = [], []
    for i, (x, y) in enumerate(pts):
        if i == 0:
            d = seg[0]
        elif i == len(pts) - 1:
            d = seg[-1]
        else:
            d = seg[i - 1] / np.linalg.norm(seg[i - 1]) + seg[i] / np.linalg.norm(seg[i])
        d = d / np.linalg.norm(d)
        nx, ny = -d[1], d[0]
        verts.append((x - nx * width / 2, y - ny * width / 2, z))
        verts.append((x + nx * width / 2, y + ny * width / 2, z))
        uvs.append((s[i] / repeat_m, 0.0))
        uvs.append((s[i] / repeat_m, 1.0))
    faces = []
    for i in range(len(pts) - 1):
        a, b, c, d = 2 * i, 2 * i + 1, 2 * i + 2, 2 * i + 3
        faces.append(((a, a, 0), (c, c, 0), (d, d, 0)))
        faces.append(((a, a, 0), (d, d, 0), (b, b, 0)))
    write_obj(path, verts, uvs, [(0, 0, 1)], faces, comment)


def dome_mesh(path, a, b, c, rings=12, segs=32, door=True):
    """Pop-up dome tent: half ellipsoid with semi-axes a (x), b (y), c (height) standing on z = 0.

    Texture coordinates: u = position around the tent (0 at +x, counter-clockwise), v = height fraction
    (0 at the ground, 1 at the top). door=True leaves an arched opening on the +x side (the tent is "open").
    """
    verts, uvs, normals = [], [], []
    for r in range(rings + 1):
        t = r / rings                                   # 0 = ground ring, 1 = apex
        lat = t * math.pi / 2
        for s in range(segs + 1):
            lon = 2 * math.pi * s / segs
            x = a * math.cos(lat) * math.cos(lon)
            y = b * math.cos(lat) * math.sin(lon)
            z = c * math.sin(lat)
            verts.append((x, y, z))
            uvs.append((s / segs, t))
            n = np.array([x / a ** 2, y / b ** 2, z / c ** 2])
            normals.append(tuple(n / (np.linalg.norm(n) + 1e-12)))
    faces = []
    for r in range(rings):
        for s in range(segs):
            i0 = r * (segs + 1) + s
            i1 = i0 + 1
            i2 = i0 + segs + 1
            i3 = i2 + 1
            q = [verts[i0], verts[i1], verts[i2], verts[i3]]
            cx = sum(v[0] for v in q) / 4
            cy = sum(v[1] for v in q) / 4
            cz = sum(v[2] for v in q) / 4
            if door and cx > 0.45 * a and abs(cy) < 0.34 * b and cz < 0.78 * c:
                continue                                 # the open door
            faces.append(((i0, i0, i0), (i1, i1, i1), (i3, i3, i3)))
            faces.append(((i0, i0, i0), (i3, i3, i3), (i2, i2, i2)))
    write_obj(path, verts, uvs, normals, faces, f'pop-up dome tent {2 * a:.2f} x {2 * b:.2f} x {c:.2f} m, door on +x')
