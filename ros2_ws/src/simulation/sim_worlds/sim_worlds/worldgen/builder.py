"""
sim_worlds/worldgen/builder.py -- PURPOSE: collect everything that goes into one world (objects, grass patches,
trees, search areas, the hiker and the tent) and write the four files of a world:

  worlds/<name>.sdf                  the Gazebo world
  config/<name>.yaml                 what the bringup needs (world file, SITL home, spawn, mission, truth, ...)
  truth/<name>.yaml                  where every target and distractor really is (for scoring)
  missions/<name>_survey.waypoints   the search mission (QGC WPL 110, the team's shape)

It also writes the models shared by all worlds into models/ (write_shared_models): the grass ground, the
take-off pad, the runway strip, the grass/dirt patch pictures and the pop-up tent. Those pictures are painted
with a FIXED seed, so every world (and every --seed) uses the same files; they are only re-painted when
missing or when asked (--textures).
"""

import datetime
import json
import math
import os

import numpy as np

from sim_worlds import geo, mission, planner
from sim_worlds.truth import CLASS_IDS
from sim_worlds.worldgen import assets, meshes, primitives, sdf, textures, world
from sim_worlds.worldgen.sdf import xml_comment

SHARED_TEXTURE_SEED = 2026          #: seed of every shared picture (independent of the layout --seed)
GROUND_HALF_M = 6000.0              #: the ground covers a 12 km square (past the GUI far clip: no visible edge)
GRASS_REPEAT_M = 160.0              #: the 4096 px grass picture covers 160 x 160 m (3.9 cm per pixel)
PAD_SIZE_M = 12.2                   #: 40 x 40 ft take-off pad (SUAS "Runway 2")
PAD_TOP_M = 0.02                    #: the pad is a 2 cm concrete slab
RUNWAY_LENGTH_M, RUNWAY_WIDTH_M = 152.4, 12.2   #: 500 x 40 ft asphalt strip (SUAS "Runway 1")
PATCH_VARIANTS = {'lush': 2, 'dry': 3, 'dirt': 3}       #: grass patches of each kind (pictures)
PATCH_PX = {'lush': 1024, 'dry': 1024, 'dirt': 512}
PATCH_Z = {'lush': 0.040, 'dry': 0.048, 'dirt': 0.056}   #: patches float a few cm above the grass (no flicker)
TENT_MODEL = 'sim_worlds_tent'


def write_model_files(model_dir, name, link_body, purpose, description):
    """Write model.sdf (with a PURPOSE comment) and model.config of a shared model."""
    with open(os.path.join(model_dir, 'model.sdf'), 'w', encoding='utf-8', newline='\n') as f:
        f.write(f'''<?xml version="1.0"?>
<!-- models/{name}/model.sdf - PURPOSE: {xml_comment(purpose)}
     GENERATED by sim_worlds/worldgen/builder.py (write_shared_models) - do not edit by hand. -->
<sdf version="1.9">
  <model name="{name}">
    <static>true</static>
    <link name="link">
{link_body}
    </link>
  </model>
</sdf>
''')
    with open(os.path.join(model_dir, 'model.config'), 'w', encoding='utf-8', newline='\n') as f:
        f.write(f'''<?xml version="1.0"?>
<!-- models/{name}/model.config - PURPOSE: tells Gazebo the name and file of this model (model://{name}). -->
<model>
  <name>{name}</name>
  <version>1.0</version>
  <sdf version="1.9">model.sdf</sdf>
  <author>
    <name>sim_worlds world generator (SUAS team)</name>
  </author>
  <description>{description}</description>
</model>
''')


def write_shared_models(models_dir, force=False, log=print):
    """Write the models every world uses into models_dir (skips pictures that already exist unless force)."""
    rng = np.random.default_rng(SHARED_TEXTURE_SEED)

    def mdir(*parts):
        d = os.path.join(models_dir, *parts)
        os.makedirs(d, exist_ok=True)
        return d

    def need(path):
        return force or not os.path.isfile(path)

    # ground ------------------------------------------------------------------------------------------------
    d = mdir('sim_worlds_ground')
    mdir('sim_worlds_ground', 'meshes')
    mdir('sim_worlds_ground', 'materials', 'textures')
    for old in [f'meshes/tiles_{k}.{e}' for k in range(4) for e in ('obj', 'mtl')] + ['meshes/far.obj', 'meshes/far.mtl'] +             [f'materials/textures/grass_{k}.jpg' for k in range(4)]:
        if os.path.isfile(os.path.join(d, old)):                 # files of an earlier experiment (tile variants)
            os.remove(os.path.join(d, old))
    meshes.ground_mesh(os.path.join(d, 'meshes', 'ground.obj'), GROUND_HALF_M, 1000.0, GRASS_REPEAT_M)
    tex = os.path.join(d, 'materials', 'textures', 'grass_albedo.jpg')
    if need(tex):
        log('  painting the grass (4096 x 4096) ...')
        textures.save_jpg(textures.grass_quilt(np.random.default_rng(SHARED_TEXTURE_SEED + 1), 4096), tex, quality=84)
    write_model_files(d, 'sim_worlds_ground', f'''      <collision name="collision">
        <geometry>
          <plane><normal>0 0 1</normal><size>{2 * GROUND_HALF_M:.0f} {2 * GROUND_HALF_M:.0f}</size></plane>
        </geometry>
        <surface><friction><ode><mu>1.0</mu><mu2>1.0</mu2></ode></friction></surface>
      </collision>
      <visual name="grass">
        <cast_shadows>false</cast_shadows>
        <geometry><mesh><uri>meshes/ground.obj</uri></mesh></geometry>
        <material>
          <ambient>1 1 1 1</ambient>
          <diffuse>1 1 1 1</diffuse>
          <specular>0.04 0.04 0.04 1</specular>
          <pbr><metal>
            <albedo_map>materials/textures/grass_albedo.jpg</albedo_map>
            <roughness>0.97</roughness><metalness>0.0</metalness>
          </metal></pbr>
        </material>
      </visual>''',
                      f'flat grass ground, {2 * GROUND_HALF_M:.0f} m square, centred on the world origin: a plane for '
                      f'physics and a mesh on which the seamless grass picture repeats every {GRASS_REPEAT_M:.0f} m.',
                      'Flat pasture ground shared by the sim_worlds worlds.')

    # pad ---------------------------------------------------------------------------------------------------
    d = mdir('sim_worlds_pad')
    mdir('sim_worlds_pad', 'meshes')
    mdir('sim_worlds_pad', 'materials', 'textures')
    meshes.quad_mesh(os.path.join(d, 'meshes', 'pad.obj'), PAD_SIZE_M, PAD_SIZE_M, 'take-off pad top surface', PAD_TOP_M)
    tex = os.path.join(d, 'materials', 'textures', 'pad_albedo.png')
    if need(tex):
        textures.save_png(textures.pad_texture(rng, PAD_SIZE_M, 1024), tex)
    write_model_files(d, 'sim_worlds_pad', f'''      <collision name="collision">
        <pose>0 0 {PAD_TOP_M / 2:.3f} 0 0 0</pose>
        <geometry><box><size>{PAD_SIZE_M} {PAD_SIZE_M} {PAD_TOP_M}</size></box></geometry>
        <surface><friction><ode><mu>1.0</mu><mu2>1.0</mu2></ode></friction></surface>
      </collision>
      <visual name="concrete">
        <geometry><mesh><uri>meshes/pad.obj</uri></mesh></geometry>
        <material>
          <ambient>1 1 1 1</ambient>
          <diffuse>1 1 1 1</diffuse>
          <specular>0.1 0.1 0.1 1</specular>
          <pbr><metal><albedo_map>materials/textures/pad_albedo.png</albedo_map>
            <roughness>0.85</roughness><metalness>0.0</metalness></metal></pbr>
        </material>
      </visual>''',
                 f'the take-off / landing pad: a {PAD_SIZE_M} m square concrete slab ({PAD_TOP_M * 100:.0f} cm thick) with '
                 'a white H. Its centre is the world origin = SITL home.',
                 'SUAS-style 40 x 40 ft VTOL pad. The drone starts here.')

    # runway ------------------------------------------------------------------------------------------------
    d = mdir('sim_worlds_runway')
    mdir('sim_worlds_runway', 'meshes')
    mdir('sim_worlds_runway', 'materials', 'textures')
    meshes.quad_mesh(os.path.join(d, 'meshes', 'runway.obj'), RUNWAY_LENGTH_M, RUNWAY_WIDTH_M, 'runway surface', 0.02)
    tex = os.path.join(d, 'materials', 'textures', 'runway_albedo.jpg')
    if need(tex):
        textures.save_jpg(textures.runway_texture(rng, RUNWAY_LENGTH_M, RUNWAY_WIDTH_M), tex, quality=85)
    write_model_files(d, 'sim_worlds_runway', f'''      <visual name="asphalt">
        <geometry><mesh><uri>meshes/runway.obj</uri></mesh></geometry>
        <material>
          <ambient>1 1 1 1</ambient>
          <diffuse>1 1 1 1</diffuse>
          <specular>0.1 0.1 0.1 1</specular>
          <pbr><metal><albedo_map>materials/textures/runway_albedo.jpg</albedo_map>
            <roughness>0.9</roughness><metalness>0.0</metalness></metal></pbr>
        </material>
      </visual>''',
                 f'a {RUNWAY_LENGTH_M} x {RUNWAY_WIDTH_M} m asphalt runway with markings (visual only, the ground plane '
                 'carries the weight). Long axis = model x.',
                 'SUAS-style 500 x 40 ft asphalt runway strip.')

    # grass / dirt patches -----------------------------------------------------------------------------------
    d = mdir('sim_worlds_decals')
    mdir('sim_worlds_decals', 'meshes')
    mdir('sim_worlds_decals', 'materials', 'textures')
    meshes.quad_mesh(os.path.join(d, 'meshes', 'quad.obj'), comment='unit quad for ground patches (scale it)')
    for kind, n in PATCH_VARIANTS.items():
        for i in range(n):
            tex = os.path.join(d, 'materials', 'textures', f'{kind}_{i}.png')
            if need(tex):
                textures.save_png(textures.patch_decal(np.random.default_rng(SHARED_TEXTURE_SEED + 10 + 7 * i +
                                                                             len(kind)), PATCH_PX[kind], kind), tex)
    write_model_files(d, 'sim_worlds_decals', '',
                 'holds the pictures of the dry-grass, lush-grass and bare-dirt patches and the quad they are drawn '
                 'on. Not a model to spawn: the worlds reference its files directly.',
                 'Ground patch pictures (RGBA cut-outs) used by the sim_worlds worlds.')

    # pop-up tent (the search target) ------------------------------------------------------------------------
    d = mdir(TENT_MODEL)
    mdir(TENT_MODEL, 'meshes')
    mdir(TENT_MODEL, 'materials', 'textures')
    a, b, c = primitives.TENT_SIZE
    meshes.dome_mesh(os.path.join(d, 'meshes', 'dome.obj'), a / 2, b / 2, c)
    for i, (cname, (col, acc)) in enumerate(primitives.TENT_COLOURS.items()):
        tex = os.path.join(d, 'materials', 'textures', f'tent_{cname}.jpg')
        if need(tex):
            textures.save_jpg(textures.tent_fabric(np.random.default_rng(SHARED_TEXTURE_SEED + 40 + i), col, acc), tex,
                              quality=88)
    body = '\n'.join(sdf.part_xml(p) for p in tent_parts('blue', model_relative=True)[0])
    write_model_files(d, TENT_MODEL, body,
                 f'the search TARGET tent: an open pop-up dome tent {a} x {b} x {c} m (door on +x, open). '
                 'This file is a stand-alone blue tent; the worlds draw it inline in other colours.',
                 'Open pop-up dome tent (SUAS search target).')


def tent_parts(colour, model_relative=False):
    """Parts of the open pop-up tent in one of primitives.TENT_COLOURS. Returns (parts, meta)."""
    col, _ = primitives.TENT_COLOURS[colour]
    base = '' if model_relative else f'model://{TENT_MODEL}/'
    return primitives.tent_parts(f'{base}meshes/dome.obj', f'{base}materials/textures/tent_{colour}.jpg', col)


def primitive_tree(rng, height):
    """Offline fallback tree: a trunk and three dark-green ellipsoid crowns (about `height` m tall)."""
    crown = height * 0.42
    parts = [sdf.part('trunk', 'cylinder', (height * 0.035, height * 0.45), (0, 0, height * 0.225),
                      color=primitives.BARK)]
    for i in range(3):
        ox, oy = rng.uniform(-crown * 0.25, crown * 0.25, 2)
        parts.append(sdf.part(f'crown_{i}', 'ellipsoid', (crown * rng.uniform(0.7, 1.0), crown * rng.uniform(0.7, 1.0),
                                                          crown * 0.6), (ox, oy, height * 0.62 + i * 0.05 * height),
                              color=primitives.BUSH_GREENS[int(rng.integers(len(primitives.BUSH_GREENS)))],
                              roughness=0.95))
    return parts


class WorldBuilder:
    """Collects one world and writes its files.

    name: world/config name ('runway'). home: geo.Home of the world origin. seed: layout seed (only recorded).
    asset_mode: 'fuel' (realistic Fuel meshes, default) or 'primitive' (simple shapes, works offline).
    """

    def __init__(self, name, home, seed, asset_mode='fuel', description=''):
        if asset_mode not in ('fuel', 'primitive'):
            raise ValueError('asset_mode must be "fuel" or "primitive"')
        self.name = name
        self.home = home
        self.seed = seed
        self.asset_mode = asset_mode
        self.description = description
        self.objects = []
        self.patches = []
        self.tree_groups = {}
        self.includes = []
        self.search_areas = []
        self.spawn = {'x': 0.0, 'y': 0.0, 'z': 0.25, 'yaw': math.pi / 2}
        self.gui_camera = world.look_at((-40.0, -60.0, 45.0), (20.0, 60.0, 0.0))
        self.follow_offset = (-12.0, 0.0, 6.0)
        self.survey = None
        self.extra_missions = []
        self.extra_truth = {}
        self.used_assets = set()
        self._rng_fallback = np.random.default_rng(seed + 99)

    # ---- adding things -------------------------------------------------------------------------------------
    def add_object(self, name, parts, x, y, yaw=0.0, z=0.0, role='scenery', cls='object', kind='', area=None,
                   size=None, center=None, model='primitive', meta=None, description=''):
        """Add one static object. role: 'target' (must be found), 'distractor' (listed in the truth file) or
        'scenery' (not listed). cls: detector class ('person', 'tent', 'object'). size: [sx, sy, sz] bounding
        box in the object frame; center: its centre (object frame, default (0, 0, sz/2))."""
        if any(o['name'] == name for o in self.objects):
            raise ValueError(f'duplicate object name {name}')
        size = list(size) if size is not None else None
        if center is None and size is not None:
            center = [0.0, 0.0, size[2] / 2.0]
        self.objects.append({'name': name, 'parts': parts, 'x': float(x), 'y': float(y), 'z': float(z),
                             'yaw': float(yaw), 'role': role, 'cls': cls, 'kind': kind, 'area': area, 'size': size,
                             'center': center, 'model': model, 'meta': dict(meta or {}), 'description': description})

    def add_asset(self, key, name, x, y, yaw=0.0, scale=1.0, role='scenery', area=None, collision=True, meta=None,
                  fallback=None):
        """Add a catalogue asset (worldgen.assets) or, in primitive mode, fallback() -> (parts, meta)."""
        a = assets.asset(key)
        if self.asset_mode == 'fuel' or fallback is None:
            parts = assets.asset_parts(key, scale, collision)
            size, center, model = a.size(scale), a.center(scale), a.model.model_url
            self.used_assets.add(key)
        else:
            parts, fmeta = fallback()
            size = fmeta['size']
            center, model = None, 'primitive'
        self.add_object(name, parts, x, y, yaw, role=role, cls=a.detector_class, kind=a.kind, area=area, size=size,
                        center=center, model=model, meta=meta, description=a.description)

    def add_hiker(self, pose, name, x, y, yaw, area, meta=None):
        """Add the hiker (SUAS mannequin, detector class 'person', a TARGET) in one of assets.HIKER_POSES."""
        meta = dict(meta or {}, pose=pose)
        if self.asset_mode == 'fuel':
            self.add_asset(f'hiker_{pose}', name, x, y, yaw, role='target', area=area, meta=meta)
        else:
            cols = {k: primitives.pick(self._rng_fallback, pal)[1] for k, pal in
                    (('shirt', primitives.SHIRT_COLOURS), ('pants', primitives.PANTS_COLOURS),
                     ('skin', primitives.SKIN_TONES), ('hair', primitives.HAIR_COLOURS))}
            parts, m = primitives.mannequin_parts(self._rng_fallback, pose, cols)
            self.add_object(name, parts, x, y, yaw, role='target', cls='person', kind='mannequin', area=area,
                            size=m['size'], model='primitive', meta=meta, description=f'mannequin ({pose})')

    def add_tent(self, name, x, y, yaw, colour, area, meta=None):
        """Add the open pop-up tent (detector class 'tent', a TARGET)."""
        parts, m = tent_parts(colour)
        a, b, c = primitives.TENT_SIZE
        self.add_object(name, parts, x, y, yaw, role='target', cls='tent', kind='tent', area=area,
                        size=[a, b, c], center=[0.0, 0.0, c / 2.0], model=f'model://{TENT_MODEL}',
                        meta=dict(meta or {}, colour=colour, door='open, on the local +x side'),
                        description=f'open pop-up dome tent ({colour})')

    def add_patch(self, kind, x, y, size, yaw, variant=0):
        """Add a ground patch: kind 'dry' or 'dirt', size = diameter-ish in metres."""
        self.patches.append({'kind': kind, 'variant': variant % PATCH_VARIANTS[kind], 'x': x, 'y': y, 'size': size,
                             'yaw': yaw})

    def add_tree(self, group, key, x, y, yaw, scale):
        """Add a tree (assets 'oak_tree' / 'pine_tree') to a named group (one static model per group).
        scale: a number, or (sx, sy, sz) (a low wide oak reads as a bush)."""
        self.tree_groups.setdefault(group, []).append((key, float(x), float(y), float(yaw), assets.scale3(scale)))
        if self.asset_mode == 'fuel':
            self.used_assets.add(key)

    def add_include(self, name, uri, xyz, rpy=(0.0, 0.0, 0.0)):
        """Add an <include> of a shared model (ground, pad, runway, creek ...)."""
        self.includes.append((name, uri, xyz, rpy))

    def add_search_area(self, name, rect, note=''):
        """Declare a search area (survey.Rect): it goes into the config and truth files and the mission."""
        self.search_areas.append({'name': name, 'rect': rect, 'note': note})

    def area(self, name):
        """The survey.Rect of a declared search area."""
        for a in self.search_areas:
            if a['name'] == name:
                return a['rect']
        raise KeyError(name)

    # ---- output --------------------------------------------------------------------------------------------
    def _patch_model(self):
        parts = []
        for i, p in enumerate(sorted(self.patches, key=lambda q: PATCH_Z[q['kind']])):
            z = PATCH_Z[p['kind']] + 0.0007 * (i % 6)
            parts.append(sdf.part(f'{p["kind"]}_{i}', 'mesh', xyz=(p['x'], p['y'], z), rpy=(0.0, 0.0, p['yaw']),
                                  color=(1.0, 1.0, 1.0), uri='model://sim_worlds_decals/meshes/quad.obj',
                                  scale=(p['size'], p['size'], 1.0),
                                  albedo=f'model://sim_worlds_decals/materials/textures/{p["kind"]}_{p["variant"]}.png',
                                  cast_shadows=False, roughness=0.95))
        return sdf.model_xml('ground_patches', parts, comment='dry-grass and bare-dirt patches (pictures on the ground)')

    def _tree_models(self):
        out = []
        rng = np.random.default_rng(self.seed + 7)
        for group, trees in self.tree_groups.items():
            parts = []
            for i, (key, x, y, yaw, scale) in enumerate(trees):
                if self.asset_mode == 'fuel':
                    tp = assets.asset_parts(key, scale, collision=False, name_prefix=f't{i}_')
                else:
                    a = assets.asset(key)
                    tp = primitive_tree(rng, (a.bbox_max[2] - a.bbox_min[2]) * scale[2])
                    tp = [dict(p, name=f't{i}_{p["name"]}') for p in tp]
                parts += sdf.transform_parts(tp, sdf.rpy_to_matrix(0.0, 0.0, yaw), (x, y, 0.0))
            out.append(sdf.model_xml(f'trees_{group}', parts, comment=f'{len(trees)} trees: {group}'))
        return out

    def world_sdf(self, purpose_lines):
        """The complete world file text."""
        gui = world.gui_xml(self.gui_camera, follow_offset=self.follow_offset)
        text = [world.header(self.name, self.home, purpose_lines, gui), '\n    <!-- ground, pad, runway -->\n']
        for name, uri, xyz, rpy in self.includes:
            text.append(sdf.include_xml(name, uri, xyz, rpy) + '\n')
        if self.patches:
            text.append('\n' + self._patch_model() + '\n')
        text.append('\n    <!-- objects: the hiker and the tent (targets), people, vehicles, debris, markers -->\n')
        for o in self.objects:
            comment = f'{o["role"].upper()}: {o["description"] or o["kind"]}' if o['role'] != 'scenery' else None
            text.append(sdf.model_xml(o['name'], o['parts'], (o['x'], o['y'], o['z']), o['yaw'], comment=comment) + '\n')
        if self.tree_groups:
            text.append('\n    <!-- trees (visual only) -->\n')
            text += [m + '\n' for m in self._tree_models()]
        text.append(world.footer())
        return ''.join(text)

    def _entry(self, o):
        lat, lon = geo.enu_to_latlon(o['x'], o['y'], self.home)
        lat84, lon84 = geo.enu_to_wgs84(o['x'], o['y'], 0.0, self.home)[:2]
        c, s = math.cos(o['yaw']), math.sin(o['yaw'])
        cx, cy, cz = o['center'] if o['center'] is not None else (0.0, 0.0, 0.0)
        e = {'id': o['name'], 'class': o['cls'], 'class_id': CLASS_IDS.get(o['cls'], '2'), 'kind': o['kind'],
             'description': o['description'], 'area': o['area'],
             'x': round(o['x'], 3), 'y': round(o['y'], 3), 'z': round(o['z'], 3), 'yaw': round(o['yaw'], 4),
             'lat': round(lat, 8), 'lon': round(lon, 8), 'alt_msl': round(self.home.alt + o['z'], 2),
             'lat_wgs84': round(lat84, 8), 'lon_wgs84': round(lon84, 8),
             'size': [round(v, 3) for v in o['size']] if o['size'] else None,
             'center': [round(o['x'] + cx * c - cy * s, 3), round(o['y'] + cx * s + cy * c, 3), round(o['z'] + cz, 3)],
             'center_z': round(o['z'] + cz, 3),
             'distance_from_home_m': round(math.hypot(o['x'], o['y']), 1), 'model': o['model']}
        e.update({k: v for k, v in o['meta'].items() if k not in e})
        return e

    def truth(self):
        """The truth dictionary (see sim_worlds/truth.py and the README for every field)."""
        areas = []
        for a in self.search_areas:
            r = a['rect']
            corners = r.corners()
            areas.append({'name': a['name'], 'note': a['note'], 'center': [round(r.cx, 3), round(r.cy, 3)],
                          'size': [round(r.length, 3), round(r.width, 3)], 'yaw': round(r.yaw, 4),
                          'corners_xy': [[round(x, 3), round(y, 3)] for x, y in corners],
                          'corners_latlon': [[round(v, 8) for v in geo.enu_to_latlon(x, y, self.home)] for x, y in corners]})
        targets = [self._entry(o) for o in self.objects if o['role'] == 'target']
        distractors = [self._entry(o) for o in self.objects if o['role'] == 'distractor']
        counts = {}
        for o in self.objects:
            counts[o['kind'] or 'other'] = counts.get(o['kind'] or 'other', 0) + 1
        counts['trees'] = sum(len(v) for v in self.tree_groups.values())
        counts['ground_patches'] = len(self.patches)
        t = {'world_name': self.name,
             'generator': {'script': f'sim_worlds/scripts/build_{self.name}.py', 'seed': self.seed,
                           'assets': self.asset_mode, 'generated': datetime.date.today().isoformat()},
             'frame': 'Gazebo world frame, ENU: x = metres east of the origin, y = metres north, z = metres up; '
                      'origin = centre of the take-off pad at ground level (= SITL home)',
             'latlon_convention': 'lat/lon = what ArduPilot SITL (and so /mavros/global_position/global and the '
                                  'photo names) reports directly above the point; lat_wgs84/lon_wgs84 = exact WGS84 '
                                  '(what a Gazebo NavSat sensor reports). They differ by about 1 m at most here.',
             'home': {'lat': self.home.lat, 'lon': self.home.lon, 'alt_msl': self.home.alt, 'heading': self.home.heading},
             'classes': {'person': CLASS_IDS['person'], 'tent': CLASS_IDS['tent']},
             'entry_fields': 'id = model name in Gazebo; x/y/z/yaw = object origin (m, rad); size = bounding box '
                             '[sx, sy, sz] in the object frame (before yaw); center = world position of the box '
                             'centre; class/class_id = what the team detector (detection/new_od.py) would call it',
             'search_areas': areas, 'targets': targets, 'distractors': distractors, 'counts': counts}
        t.update(self.extra_truth)
        return t

    def write(self, out_dir, purpose_lines, mission_settings=None, log=print):
        """Write worlds/, config/, truth/ and missions/ files into the package folder out_dir.

        mission_settings: list of (area_name, suffix, planner.SurveySettings); the first one must have suffix ''
        and becomes the contract mission missions/<name>_survey.waypoints, the others are extras
        (missions/<name><suffix>_survey.waypoints).
        Returns a dict of written paths and the mission summaries.
        """
        import yaml
        paths = {}
        for sub in ('worlds', 'config', 'truth', 'missions'):
            os.makedirs(os.path.join(out_dir, sub), exist_ok=True)
        p = os.path.join(out_dir, 'worlds', f'{self.name}.sdf')
        with open(p, 'w', encoding='utf-8', newline='\n') as f:
            f.write(self.world_sdf(purpose_lines))
        paths['world'] = p
        summaries = []
        for i, (area_name, suffix, settings) in enumerate(mission_settings or []):
            items, plan, speed = planner.plan_survey_mission(self.home, self.area(area_name), settings)
            problems = mission.check_team_shape(items, alt_min=settings.altitude_m - 1e-6,
                                                alt_max=settings.altitude_m + 1e-6)
            if problems:
                raise RuntimeError(f'mission for {area_name} breaks the team shape: {problems}')
            mp = os.path.join(out_dir, 'missions', f'{self.name}{suffix}_survey.waypoints')
            mission.write_waypoints(mp, items)
            s = planner.summary(items, plan, speed, self.home)
            s.update({'area': area_name, 'file': f'missions/{self.name}{suffix}_survey.waypoints',
                      'settings': {'altitude_m': settings.altitude_m, 'sidelap': settings.sidelap,
                                   'frontlap': settings.frontlap, 'photo_interval_s': settings.photo_interval_s}})
            summaries.append(s)
            paths[f'mission{suffix}'] = mp
            log(f'  mission {os.path.basename(mp)}: {s["items"]} items, {s["lanes"]} lanes '
                f'{s["lane_spacing_m"]} m apart, {s["speed_mps"]} m/s, survey {s["survey_path_m"]} m')
            log('    ' + mission.describe(items, self.home).replace('\n', '\n    '))
        p = os.path.join(out_dir, 'truth', f'{self.name}.yaml')
        with open(p, 'w', encoding='utf-8', newline='\n') as f:
            f.write(f'# truth/{self.name}.yaml -- PURPOSE: ground truth of the "{self.name}" world: where the hiker '
                    f'(mannequin) and the tent\n# REALLY are, plus the distractors (people, vehicles, debris, bushes), so '
                    f'a run can be scored automatically.\n# NEVER give this file to the detector. GENERATED by '
                    f'sim_worlds/scripts/build_{self.name}.py (seed {self.seed}) - edit that\n# script and re-run it.\n')
            yaml.safe_dump(self.truth(), f, sort_keys=False, default_flow_style=None, width=120, allow_unicode=True)
        paths['truth'] = p
        p = os.path.join(out_dir, 'config', f'{self.name}.yaml')
        with open(p, 'w', encoding='utf-8', newline='\n') as f:
            f.write(self.config_text(summaries, mission_settings or []))
        paths['config'] = p
        paths['summaries'] = summaries
        return paths

    def config_text(self, summaries, mission_settings):
        """config/<name>.yaml text (hand formatted so every field carries a comment)."""
        sp = self.spawn
        lines = [
            f'# config/{self.name}.yaml -- PURPOSE: everything the bringup needs to start the "{self.name}" world: which SDF',
            '# to load, where SITL\'s home is (it MUST equal the world\'s <spherical_coordinates>), where the drone spawns,',
            '# which survey mission to upload and where the ground-truth list of targets is.',
            f'# GENERATED by sim_worlds/scripts/build_{self.name}.py (seed {self.seed}, assets {self.asset_mode}) - edit that',
            '# script and re-run it instead of editing this file. All file paths are relative to the sim_worlds share',
            '# folder:  $(ros2 pkg prefix --share sim_worlds)/<path>',
            f'world_name: {self.name}                        # <world name="..."> inside the SDF (gz service names use it)',
            f'description: "{self.description}"',
            f'world_file: worlds/{self.name}.sdf',
            f'home: "{self.home.sitl_string()}"   # lat,lon,alt_msl_m,heading_deg -> SITL --home',
            f'spawn: {{x: {sp["x"]:.3f}, y: {sp["y"]:.3f}, z: {sp["z"]:.3f}, yaw: {sp["yaw"]:.4f}}}'
            '   # drone start pose (m, rad, ENU); yaw 1.5708 = nose north',
            f'mission: missions/{self.name}_survey.waypoints',
            f'truth: truth/{self.name}.yaml',
            'gui:                                       # what the world\'s GUI shows (worldgen/world.py)',
            '  follow_target: iris                      # the bringup calls /gui/follow with this entity name',
            f'  follow_offset: [{", ".join(f"{v:g}" for v in self.follow_offset)}]          # m, in the drone frame (behind, left, up)',
            f'  camera_topic: {world.CAMERA_TOPIC}   # shown in the "Drone camera (live)" panel',
            'search_areas:                              # rectangles the drone must search (local metres, ENU)',
        ]
        for a in self.search_areas:
            r = a['rect']
            lines += [f'  - name: {a["name"]}',
                      f'    note: "{a["note"]}"',
                      f'    center: [{r.cx:.3f}, {r.cy:.3f}]          # m',
                      f'    size: [{r.length:.3f}, {r.width:.3f}]          # m: [along the lanes, across the lanes]',
                      f'    yaw: {r.yaw:.4f}                       # rad: lane direction (0 = east, 1.5708 = north)']
        if mission_settings:
            area0, _, s0 = mission_settings[0]
            lines += ['survey:                                    # how the contract mission was made '
                      '(scripts/make_mission.py re-reads this)',
                      f'  area: {area0}',
                      f'  altitude_m: {s0.altitude_m:g}                    # survey height above home',
                      f'  sidelap: {s0.sidelap:g}                         # photo overlap between lanes',
                      f'  frontlap: {s0.frontlap:g}                        # photo overlap along a lane',
                      f'  photo_interval_s: {s0.photo_interval_s:g}                 # one photo every N s (real pipeline)',
                      f'  speed_mps: {"null" if s0.speed_mps is None else s0.speed_mps}'
                      '                      # null = automatic from frontlap; 0 = no DO_CHANGE_SPEED',
                      f'  max_speed_mps: {s0.max_speed_mps:g}',
                      f'  lead_in_s: {s0.lead_in_s:g}                         # lane 1 starts this many s of flight '
                      'early (team camera set-up after DigiCamCtrl)',
                      f'  camera: {{hfov_rad: {s0.hfov_rad:g}, width_px: {s0.width_px}, height_px: {s0.height_px}}}',
                      '  planned:                                 # facts about the written mission']
            for k, v in summaries[0].items():
                if k in ('settings', 'area'):
                    continue
                lines.append(f'    {k}: {json.dumps(v)}')        # JSON values are valid YAML
            if len(summaries) > 1:
                lines.append('extra_missions:                            # more missions for other search areas')
                for (area, suffix, s), summ in zip(mission_settings[1:], summaries[1:]):
                    lines += [f'  - area: {area}', f'    file: {summ["file"]}', f'    altitude_m: {s.altitude_m:g}',
                              f'    lanes: {summ["lanes"]}', f'    speed_mps: {summ["speed_mps"]}']
        return '\n'.join(lines) + '\n'
