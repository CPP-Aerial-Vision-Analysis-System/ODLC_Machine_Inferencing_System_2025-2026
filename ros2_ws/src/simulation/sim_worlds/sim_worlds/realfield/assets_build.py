# the three models
# ------------------------------------------------------------------------------------------------------------

def build_ground(pack, out, tiles, quality, log):
    m = _mkdirs(out, 'rf_ground')
    visuals, tris, pic_bytes, pics = [], 0, 0, 0
    t0 = time.time()
    for i, t in enumerate(tiles):
        kind = site.TILE_KINDS[t['kind']]
        px = kind['tex_px_hd'] if quality == 'hd' else kind['tex_px']
        prim, surface_tris, _all_tris = terrain.build_tile(pack, t, px)
        glb.write_glb(os.path.join(m, 'meshes', f"{t['name']}.glb"), [prim])
        pic = texture.tile_picture(pack, t, px, kind['micro'])
        pic_bytes += _save_image(os.path.join(m, 'textures', f"{t['name']}.jpg"), pic)
        pics += 1
        tris += surface_tris
        visuals.append(_visual(t['name'], 'rf_ground', f"meshes/{t['name']}.glb",
                               _pbr('rf_ground', f"textures/{t['name']}.jpg"), shadows=False))
        if (i + 1) % 20 == 0 or i + 1 == len(tiles):
            log(f'  ground: {i + 1}/{len(tiles)} tiles ({time.time() - t0:.0f} s)')
    cprim, ctiles, ctris = terrain.build_collision(pack, tiles, pack.home, log=log)
    glb.write_glb(os.path.join(m, 'meshes', 'collision.glb'), [cprim])
    collision = ('    <collision name="ground_collision"><geometry><mesh><uri>model://rf_ground/meshes/collision.glb'
                 '</uri></mesh></geometry><surface><friction><ode><mu>1.0</mu><mu2>1.0</mu2></ode></friction>'
                 '</surface></collision>')
    _write_model(out, 'rf_ground', 'The real SUAS 2026 field terrain (USGS lidar heights, NAIP aerial colour).',
                 collision + '\n' + '\n'.join(visuals))
    return {'tiles': len(tiles), 'visual_triangles': tris, 'collision_tiles': ctiles, 'collision_triangles': ctris,
            'pictures': pics, 'picture_mb': round(pic_bytes / 1e6, 1)}


def build_trees(pack, out, tiles, log):
    m = _mkdirs(out, 'rf_trees')
    near = _near_blocks(tiles)
    blocks, _tones, atlas = trees.build_tree_blocks(pack, pack.home, near)
    _save_image(os.path.join(m, 'textures', 'leaf_atlas.png'), atlas, 'PNG')
    visuals, ntrees, tris = [], 0, 0
    for blk, d in sorted(blocks.items()):
        tag = f'b{blk[0]}{blk[1]}'
        glb.write_glb(os.path.join(m, 'meshes', f'crowns_{tag}.glb'), [d['crowns']])
        visuals.append(_visual(f'crowns_{tag}', 'rf_trees', f'meshes/crowns_{tag}.glb',
                               _pbr('rf_trees', 'textures/leaf_atlas.png', roughness=0.9), shadows=True))
        if d['trunks'] is not None:
            glb.write_glb(os.path.join(m, 'meshes', f'trunks_{tag}.glb'), [d['trunks']])
            visuals.append(_visual(f'trunks_{tag}', 'rf_trees', f'meshes/trunks_{tag}.glb',
                                   _plain((0.28, 0.2, 0.14)), shadows=True))
        ntrees += d['trees']
        tris += d['triangles']
    canopy_sheets = 0
    nx = int(round((site.EXTENT[2] - site.EXTENT[0]) / site.BLOCK_M))
    ny = int(round((site.EXTENT[3] - site.EXTENT[1]) / site.BLOCK_M))
    for j in range(ny):
        for i in range(nx):
            prim, tex = trees.build_canopy_block(pack, (i, j))
            if prim is None:
                continue
            tag = f'b{i}{j}'
            glb.write_glb(os.path.join(m, 'meshes', f'canopy_{tag}.glb'), [prim])
            _save_image(os.path.join(m, 'textures', f'canopy_{tag}.jpg'), tex)
            visuals.append(_visual(f'canopy_{tag}', 'rf_trees', f'meshes/canopy_{tag}.glb',
                                   _pbr('rf_trees', f'textures/canopy_{tag}.jpg', roughness=0.95), shadows=True))
            tris += len(prim['idx']) // 3
            canopy_sheets += 1
    log(f'  trees: {ntrees:,} trees in {len(blocks)} blocks, {canopy_sheets} canopy sheets, {tris:,} triangles')
    _write_model(out, 'rf_trees', 'Every real tree of the field (lidar 2017 + aerial 2023) and the closed forest.',
                 '\n'.join(visuals))
    return {'trees': ntrees, 'blocks': len(blocks), 'canopy_sheets': canopy_sheets, 'triangles': tris}


def build_buildings(pack, out, log):
    m = _mkdirs(out, 'rf_buildings')
    groups, palette, info = structures.build_buildings(pack, log=log)
    visuals = []
    if any(g is not None for g in groups.values()):
        _save_image(os.path.join(m, 'textures', 'palette.png'), palette, 'PNG')
    for key, prim in groups.items():
        if prim is None:
            continue
        glb.write_glb(os.path.join(m, 'meshes', f'buildings_{key}.glb'), [prim])
        visuals.append(_visual(f'buildings_{key}', 'rf_buildings', f'meshes/buildings_{key}.glb',
                               _pbr('rf_buildings', 'textures/palette.png', roughness=0.85), shadows=True))
    _write_model(out, 'rf_buildings', 'The buildings of the field (outlines from OpenStreetMap / Microsoft, heights from lidar).',
                 '\n'.join(visuals))
    with open(os.path.join(m, 'buildings.json'), 'w', encoding='utf-8') as f:
        json.dump(info, f, indent=1)
    return {'buildings': len(info)}


# ------------------------------------------------------------------------------------------------------------
# entry point
# ------------------------------------------------------------------------------------------------------------

def run(out, pack_dir=None, quality='hd', if_needed=False, log=print):
    """Build rf_ground, rf_trees and rf_buildings into the models folder `out`. Returns the manifest dict."""
    if quality not in ('hd', 'standard'):
        raise SystemExit(f"[assets] ERROR: unknown quality '{quality}'. Fix: use hd or standard.")
    pack = SitePack(pack_dir)
    fp = fingerprint(pack.folder, quality)
    os.makedirs(out, exist_ok=True)
    if if_needed and _up_to_date(out, fp):
        log(f'[assets] the models in {out} are up to date (fingerprint {fp}): nothing to do')
        return None
    log(f'[assets] building the real-field models ({quality}) into {out}')
    t0 = time.time()
    tiles = site.tile_layout(pack.home)
    per_kind = ', '.join('%s: %d' % (k, sum(1 for t in tiles if t['kind'] == k)) for k in site.TILE_KINDS)
    log('  %d terrain tiles (%s)' % (len(tiles), per_kind))
    manifest = {'purpose': 'what sim_worlds/realfield/assets_build.py made; fingerprint = inputs hash for --if-needed',
                'version': VERSION, 'quality': quality, 'fingerprint': fp,
                'ground': build_ground(pack, out, tiles, quality, log),
                'trees': build_trees(pack, out, tiles, log),
                'buildings': build_buildings(pack, out, log)}
    manifest['seconds'] = round(time.time() - t0, 1)
    with open(os.path.join(out, MANIFEST), 'w', encoding='utf-8') as f:
        json.dump(manifest, f, indent=1)
    log(f'[assets] done in {manifest["seconds"]} s: {out}')
    return manifest
