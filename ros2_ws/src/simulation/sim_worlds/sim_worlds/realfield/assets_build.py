"""
sim_worlds/realfield/assets_build.py -- PURPOSE: stage 3 of the real-field pipeline: turn the compact site pack
(lidar heights, aerial colour, tree list, building outlines) into the Gazebo MODELS of the world "suas_field_real":

  rf_ground/     the terrain: one visual per tile (a .glb mesh + a baked ground picture, see terrain.py and
                 texture.py) and ONE merged physics mesh (collision.glb), so landings and payload drops touch the
                 same ground you see (a Gazebo <heightmap> misbehaved on this laptop, meshes did not)
  rf_trees/      every real tree as merged meshes per 264 m block (+ trunks near the action, + leaf colour atlas)
                 and the closed forest as canopy sheets painted with the aerial photo; no collision
  rf_buildings/  the buildings (merged meshes, a small colour palette picture for roofs and walls)

Each model folder holds model.config, model.sdf, meshes/ and textures/. A summary of what was made (counts,
triangles, picture sizes, time, an input fingerprint) goes to <models>/rf_assets_manifest.json; --if-needed uses
that fingerprint to skip the work when nothing changed. This file only ORCHESTRATES: the geometry and the picture
making live in terrain.py, texture.py, trees.py and structures.py (numpy + Pillow, no GIS libraries), and the
poles, wires, targets and the world file itself come in stage 4 (world_build.py).

quality: 'hd' (default) bakes the search-area ground pictures at 3.2 cm per pixel (2048 px per 66 m tile),
'standard' at 6.4 cm (1024 px, half the graphics memory there).
"""

import hashlib
import json
import os
import time

import numpy as np

from sim_worlds.realfield import glb, site, structures, terrain, texture, trees
from sim_worlds.realfield.sitepack import SitePack

VERSION = 1                                  #: bump when the layout of the produced models changes
MODELS = ('rf_ground', 'rf_trees', 'rf_buildings')
MANIFEST = 'rf_assets_manifest.json'
JPEG_QUALITY = 92

_CONFIG = """<?xml version="1.0"?>
<model>
  <name>{name}</name>
  <version>1.0</version>
  <sdf version="1.9">model.sdf</sdf>
  <author><name>ASTRA simulator (generated by sim_worlds/realfield/assets_build.py)</name></author>
  <description>{desc}</description>
</model>
"""


# ------------------------------------------------------------------------------------------------------------
# where to write, and "is it up to date?"
# ------------------------------------------------------------------------------------------------------------

def resolve_out(out, install, pkg):
    """The models folder: --out as given, the INSTALLED sim_worlds share/models (--install), or <pkg>/models."""
    if out:
        return os.path.abspath(out)
    if install:
        try:
            from ament_index_python.packages import get_package_share_directory
            return os.path.join(get_package_share_directory('sim_worlds'), 'models')
        except Exception as exc:                                     # noqa: BLE001
            raise SystemExit('[assets] ERROR: --install needs the built sim_worlds package (ament index said: '
                             f'{exc}). Fix: build it first (bash simulation/setup/03_build.sh) or use --out DIR.')
    return os.path.join(pkg, 'models')


def fingerprint(pack_dir, quality):
    """A short hash of everything the models depend on: the pack's pack.json, the quality, this stage's
    version and the source files of the geometry helpers."""
    h = hashlib.sha256()
    h.update(f'{VERSION}:{quality}'.encode())
    pack_json = os.path.join(pack_dir or '', 'pack.json')
    if os.path.isfile(pack_json):
        h.update(open(pack_json, 'rb').read())
    here = os.path.dirname(os.path.abspath(__file__))
    for name in ('assets_build.py', 'terrain.py', 'texture.py', 'trees.py', 'structures.py', 'glb.py', 'rtin.py', 'site.py'):
        p = os.path.join(here, name)
        if os.path.isfile(p):
            h.update(open(p, 'rb').read())
    return h.hexdigest()[:16]


def _up_to_date(out, fp):
    try:
        with open(os.path.join(out, MANIFEST), encoding='utf-8') as f:
            m = json.load(f)
        return m.get('fingerprint') == fp and all(os.path.isfile(os.path.join(out, n, 'model.sdf')) for n in MODELS)
    except (OSError, ValueError):
        return False


# ------------------------------------------------------------------------------------------------------------
# small writers
# ------------------------------------------------------------------------------------------------------------

def _mkdirs(out, name):
    for sub in ('meshes', 'textures'):
        os.makedirs(os.path.join(out, name, sub), exist_ok=True)
    return os.path.join(out, name)


def _save_image(path, rgb, fmt='JPEG'):
    from PIL import Image
    im = Image.fromarray(np.asarray(rgb, dtype=np.uint8))
    if fmt == 'JPEG':
        im.save(path, 'JPEG', quality=JPEG_QUALITY, subsampling=0, optimize=True)
    else:
        im.save(path, 'PNG', optimize=True)
    return os.path.getsize(path)


def _pbr(model, texture_rel, roughness=0.95, diffuse='1 1 1 1'):
    """A <material> with a baked picture (PBR albedo map) that no light makes shiny."""
    return (f'<material><diffuse>{diffuse}</diffuse><specular>0.02 0.02 0.02 1</specular><pbr><metal>'
            f'<albedo_map>model://{model}/{texture_rel}</albedo_map><roughness>{roughness}</roughness>'
            f'<metalness>0.0</metalness></metal></pbr></material>')


def _plain(rgb):
    r, g, b = rgb
    return f'<material><ambient>{r} {g} {b} 1</ambient><diffuse>{r} {g} {b} 1</diffuse><specular>0.02 0.02 0.02 1</specular></material>'


def _visual(name, model, mesh_rel, material, shadows):
    return (f'    <visual name="{name}"><cast_shadows>{"true" if shadows else "false"}</cast_shadows>'
            f'<geometry><mesh><uri>model://{model}/{mesh_rel}</uri></mesh></geometry>{material}</visual>')


def _write_model(out, name, desc, body):
    d = os.path.join(out, name)
    with open(os.path.join(d, 'model.config'), 'w', encoding='utf-8', newline='\n') as f:
        f.write(_CONFIG.format(name=name, desc=desc))
    with open(os.path.join(d, 'model.sdf'), 'w', encoding='utf-8', newline='\n') as f:
        f.write('<?xml version="1.0"?>\n<sdf version="1.9">\n'
                f'  <!-- {desc} Generated by sim_worlds/realfield/assets_build.py: do not edit, regenerate. -->\n'
                f'  <model name="{name}">\n    <static>true</static>\n    <link name="link">\n'
                f'{body}\n    </link>\n  </model>\n</sdf>\n')


def _near_blocks(tiles):
    """Blocks (i, j) that contain any tile finer than 'far' (names look like b<i><j>[q..][t..])."""
    return {(int(t['name'][1]), int(t['name'][2])) for t in tiles if t['kind'] != 'far'}


