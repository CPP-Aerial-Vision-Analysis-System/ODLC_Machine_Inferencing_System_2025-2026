"""
sim_worlds/realfield/world_build.py -- PURPOSE: stage 4 of the real-terrain pipeline. It writes the Gazebo world
"suas_field_real" and its three companions from the site pack:

  worlds/suas_field_real.sdf                 the world (terrain, trees and buildings models, pad, targets, props)
  config/suas_field_real.yaml                what the bringup needs (SITL home, spawn, missions, truth)
  truth/suas_field_real.yaml                 where the hiker, the tent and every distractor REALLY are (scoring)
  missions/suas_field_real_survey.waypoints  contract mission over Search Boundary 1   (+ _sb2_ for Search Boundary 2)

How it differs from the flat procedural field (scripts/build_suas_field.py):
  * the ground is the real lidar terrain (model "rf_ground", made by stage 3), so EVERY object is set on the real
    ground height, not on z = 0, and the targets are only placed where the ground is open, level and not water;
  * the trees come from the lidar/photo tree list (model "rf_trees"), so no tree is invented here; the hiker and
    the tent are kept clear of the real crowns (a bush may still stand beside the hiker, as the rules allow);
  * the flying height is derived from the real ground under each search boundary: at least 150 ft above its
    HIGHEST ground and at most 400 ft above its LOWEST ground (SUAS rule), and the lane spacing / speed are worked
    out for the camera height over the highest ground (the smallest photo footprint);
  * the sun is the sun of the aerial photo's day and hour (shadows in the photo and in Gazebo then agree);
  * the three real wooden poles inside Search Boundary 1 are put in (they are in no map database).
Everything random comes from the seed (default 2026): the same seed always gives the same targets.
Needs numpy and PyYAML (no GIS libraries). The models themselves are made by assets_build.py.
"""

