def _two(value, what, allowed):
    """Two values (SB1, SB2) from a comma string / list; None when not given (the seed then chooses)."""
    if value is None:
        return None
    vals = [v.strip() for v in (value.split(',') if isinstance(value, str) else value)]
    if len(vals) != 2 or any(v not in allowed for v in vals):
        raise ValueError(f'{what}s must be 2 of {list(allowed)}, got {value!r}')
    return vals
