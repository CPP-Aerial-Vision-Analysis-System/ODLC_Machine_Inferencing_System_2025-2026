"""
lattice_bridge/test/scenario_data.py -- PURPOSE: the real simulator worlds as test data. The clustering and
area tests are most convincing when they use the TRUE positions of the hiker, the tent, the decoy people and
the search areas of the two worlds (runway, suas_field). Those live in
ros2_ws/src/simulation/sim_worlds/{config,truth}/*.yaml, which only exist inside the full repo, but this
package's tests must also run from a clean overlay that contains nothing else. So the few numbers that are
needed are copied into data/scenario_truth.yaml (committed), and a freshness test compares that copy with the
real files whenever the repo is present.

Refresh the copy after the worlds are regenerated:

    python3 ros2_ws/src/lattice_bridge/test/scenario_data.py --write
    python3 ros2_ws/src/lattice_bridge/test/scenario_data.py --check      # exit 0 = up to date

Needs PyYAML (tests only; the library itself does not).
"""

import argparse
import sys
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
FIXTURE = HERE / 'data' / 'scenario_truth.yaml'
WORLDS = ('runway', 'suas_field')
HEADER = (
    '# data/scenario_truth.yaml -- PURPOSE: the true target, decoy and area positions of the simulator worlds,\n'
    '# copied from ros2_ws/src/simulation/sim_worlds/{config,truth}/*.yaml so the lattice_bridge tests run\n'
    '# without the rest of the repo. GENERATED by test/scenario_data.py --write: do not edit by hand.\n'
)


def sim_worlds_dir():
    """The sim_worlds package folder in the full repo, or None (clean overlay)."""
    repo = HERE.parents[3]
    candidate = repo / 'ros2_ws' / 'src' / 'simulation' / 'sim_worlds'
    return candidate if (candidate / 'truth').is_dir() else None


def extract(config: dict, truth: dict) -> dict:
    """The numbers the tests need from one world's config and truth dicts."""
    areas = []
    for item in config['search_areas']:
        areas.append({'name': item['name'], 'note': item.get('note', ''), 'center': list(item['center']),
                      'size': list(item['size']), 'yaw': item.get('yaw', 0.0)})
    boundary = truth.get('flight_boundary') or {}
    return {
        'config': {'home': config['home'], 'search_areas': areas},
        'truth': {
            'home': dict(truth['home']),
            'targets': [{'id': t['id'], 'class': t['class'], 'lat': t['lat'], 'lon': t['lon'],
                         'area': t['area']} for t in truth['targets']],
            'person_decoys': [{'id': d['id'], 'lat': d['lat'], 'lon': d['lon']}
                              for d in truth.get('distractors', []) if d.get('class') == 'person'],
            'search_areas': [{'name': a['name'], 'corners_latlon': [list(c) for c in a['corners_latlon']]}
                             for a in truth['search_areas']],
            'flight_boundary': {'latlon': [list(p) for p in boundary['latlon']]} if boundary else None,
            'altitude_rule_agl_m': dict(truth['altitude_rule_agl_m']) if 'altitude_rule_agl_m' in truth else None,
        },
    }


def build_from_repo(worlds_dir: Path) -> dict:
    """Read the real config/truth files and extract the scenario data for every world."""
    data = {}
    for world in WORLDS:
        config = yaml.safe_load((worlds_dir / 'config' / f'{world}.yaml').read_text(encoding='utf-8'))
        truth = yaml.safe_load((worlds_dir / 'truth' / f'{world}.yaml').read_text(encoding='utf-8'))
        data[world] = extract(config, truth)
    return data


def load_fixture() -> dict:
    """The committed copy."""
    return yaml.safe_load(FIXTURE.read_text(encoding='utf-8'))


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description='Write or check data/scenario_truth.yaml.')
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument('--write', action='store_true', help='rewrite the committed copy from the repo')
    group.add_argument('--check', action='store_true', help='exit 1 when the committed copy is out of date')
    args = parser.parse_args(argv)
    worlds_dir = sim_worlds_dir()
    if worlds_dir is None:
        print('sim_worlds not found (run this inside the full repo)', file=sys.stderr)
        return 2
    fresh = build_from_repo(worlds_dir)
    if args.write:
        FIXTURE.parent.mkdir(exist_ok=True)
        with open(FIXTURE, 'w', encoding='utf-8', newline='\n') as handle:
            handle.write(HEADER)
            yaml.safe_dump(fresh, handle, sort_keys=False, default_flow_style=None, width=110)
        print(f'wrote {FIXTURE}')
        return 0
    if load_fixture() == fresh:
        print('scenario_truth.yaml is up to date')
        return 0
    print('scenario_truth.yaml is OUT OF DATE: run  python3 test/scenario_data.py --write', file=sys.stderr)
    return 1


if __name__ == '__main__':
    sys.exit(main())
